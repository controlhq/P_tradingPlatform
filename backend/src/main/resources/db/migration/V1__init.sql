-- =====================================================================
-- V1: initial schema
-- Money: NUMERIC(19,4). Share quantities: BIGINT (whole shares).
-- All timestamps: TIMESTAMPTZ (UTC).
-- =====================================================================

-- ---------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    role            VARCHAR(20)  NOT NULL DEFAULT 'USER',
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_users_email          UNIQUE (email),
    CONSTRAINT ck_users_email_lower    CHECK (email = lower(email)),
    CONSTRAINT ck_users_email_format   CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT ck_users_password_hash  CHECK (length(password_hash) > 0),
    CONSTRAINT ck_users_role           CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_users_updated_after  CHECK (updated_at >= created_at)
);

-- ---------------------------------------------------------------------
-- refresh_tokens (only a hash of the token is stored)
-- ---------------------------------------------------------------------
CREATE TABLE refresh_tokens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    token_hash      VARCHAR(64)  NOT NULL,
    expires_at      TIMESTAMPTZ  NOT NULL,
    revoked_at      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_refresh_tokens_user   FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_refresh_tokens_hash   UNIQUE (token_hash),
    CONSTRAINT ck_refresh_tokens_hash   CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_refresh_tokens_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_refresh_tokens_revoke CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);

CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id);

-- ---------------------------------------------------------------------
-- accounts (cash; one per user per currency)
-- ---------------------------------------------------------------------
CREATE TABLE accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL,
    currency        CHAR(3)       NOT NULL DEFAULT 'USD',
    balance         NUMERIC(19,4) NOT NULL DEFAULT 0,
    blocked         NUMERIC(19,4) NOT NULL DEFAULT 0,
    version         BIGINT        NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_accounts_user           FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_accounts_user_currency  UNIQUE (user_id, currency),
    CONSTRAINT ck_accounts_currency       CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_accounts_balance        CHECK (balance >= 0),
    CONSTRAINT ck_accounts_blocked        CHECK (blocked >= 0),
    CONSTRAINT ck_accounts_blocked_le_bal CHECK (blocked <= balance),
    CONSTRAINT ck_accounts_version        CHECK (version >= 0),
    CONSTRAINT ck_accounts_updated_after  CHECK (updated_at >= created_at)
);

-- ---------------------------------------------------------------------
-- instruments
-- ---------------------------------------------------------------------
CREATE TABLE instruments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol          VARCHAR(16)   NOT NULL,
    name            VARCHAR(255)  NOT NULL,
    currency        CHAR(3)       NOT NULL DEFAULT 'USD',
    active          BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT uq_instruments_symbol   UNIQUE (symbol),
    CONSTRAINT ck_instruments_symbol   CHECK (symbol ~ '^[A-Z0-9.]{1,16}$'),
    CONSTRAINT ck_instruments_name     CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_instruments_currency CHECK (currency ~ '^[A-Z]{3}$')
);

-- ---------------------------------------------------------------------
-- price_ticks
-- ---------------------------------------------------------------------
CREATE TABLE price_ticks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id   BIGINT        NOT NULL,
    price           NUMERIC(19,4) NOT NULL,
    ts              TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_price_ticks_instrument FOREIGN KEY (instrument_id) REFERENCES instruments (id) ON DELETE CASCADE,
    CONSTRAINT ck_price_ticks_price      CHECK (price > 0)
);

CREATE INDEX ix_price_ticks_instrument_ts ON price_ticks (instrument_id, ts DESC);

-- ---------------------------------------------------------------------
-- orders
-- ---------------------------------------------------------------------
CREATE TABLE orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL,
    instrument_id   BIGINT        NOT NULL,
    side            VARCHAR(4)    NOT NULL,
    type            VARCHAR(6)    NOT NULL,
    status          VARCHAR(10)   NOT NULL DEFAULT 'PENDING',
    quantity        BIGINT        NOT NULL,
    limit_price     NUMERIC(19,4),
    stop_price      NUMERIC(19,4),
    filled_price    NUMERIC(19,4),
    filled_at       TIMESTAMPTZ,
    version         BIGINT        NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_orders_user          FOREIGN KEY (user_id)       REFERENCES users (id),
    CONSTRAINT fk_orders_instrument    FOREIGN KEY (instrument_id) REFERENCES instruments (id),
    CONSTRAINT ck_orders_side          CHECK (side   IN ('BUY', 'SELL')),
    CONSTRAINT ck_orders_type          CHECK (type   IN ('MARKET', 'LIMIT', 'STOP')),
    CONSTRAINT ck_orders_status        CHECK (status IN ('PENDING', 'FILLED', 'CANCELLED', 'REJECTED')),
    CONSTRAINT ck_orders_quantity      CHECK (quantity > 0),
    CONSTRAINT ck_orders_limit_price   CHECK ((type = 'LIMIT') = (limit_price IS NOT NULL)),
    CONSTRAINT ck_orders_stop_price    CHECK ((type = 'STOP')  = (stop_price  IS NOT NULL)),
    CONSTRAINT ck_orders_limit_pos     CHECK (limit_price  IS NULL OR limit_price  > 0),
    CONSTRAINT ck_orders_stop_pos      CHECK (stop_price   IS NULL OR stop_price   > 0),
    CONSTRAINT ck_orders_filled_pos    CHECK (filled_price IS NULL OR filled_price > 0),
    CONSTRAINT ck_orders_filled_iff    CHECK ((status = 'FILLED') = (filled_price IS NOT NULL AND filled_at IS NOT NULL)),
    CONSTRAINT ck_orders_filled_pair   CHECK ((filled_price IS NULL) = (filled_at IS NULL)),
    CONSTRAINT ck_orders_version       CHECK (version >= 0),
    CONSTRAINT ck_orders_updated_after CHECK (updated_at >= created_at)
);

CREATE INDEX ix_orders_user_created ON orders (user_id, created_at);
CREATE INDEX ix_orders_instrument   ON orders (instrument_id);

-- ---------------------------------------------------------------------
-- positions (holdings; no short selling)
-- ---------------------------------------------------------------------
CREATE TABLE positions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL,
    instrument_id   BIGINT        NOT NULL,
    quantity        BIGINT        NOT NULL DEFAULT 0,
    blocked         BIGINT        NOT NULL DEFAULT 0,
    avg_price       NUMERIC(19,4) NOT NULL DEFAULT 0,
    version         BIGINT        NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_positions_user          FOREIGN KEY (user_id)       REFERENCES users (id),
    CONSTRAINT fk_positions_instrument    FOREIGN KEY (instrument_id) REFERENCES instruments (id),
    CONSTRAINT uq_positions_user_instr    UNIQUE (user_id, instrument_id),
    CONSTRAINT ck_positions_quantity      CHECK (quantity >= 0),
    CONSTRAINT ck_positions_blocked       CHECK (blocked >= 0),
    CONSTRAINT ck_positions_blocked_le_q  CHECK (blocked <= quantity),
    CONSTRAINT ck_positions_avg_price     CHECK (avg_price >= 0),
    CONSTRAINT ck_positions_version       CHECK (version >= 0),
    CONSTRAINT ck_positions_updated_after CHECK (updated_at >= created_at)
);

CREATE INDEX ix_positions_instrument ON positions (instrument_id);

-- ---------------------------------------------------------------------
-- transactions (cash ledger; amount is always positive, type gives direction)
-- ---------------------------------------------------------------------
CREATE TABLE transactions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL,
    account_id      BIGINT        NOT NULL,
    order_id        BIGINT,
    type            VARCHAR(10)   NOT NULL,
    amount          NUMERIC(19,4) NOT NULL,
    balance_after   NUMERIC(19,4) NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_transactions_user    FOREIGN KEY (user_id)    REFERENCES users (id),
    CONSTRAINT fk_transactions_account FOREIGN KEY (account_id) REFERENCES accounts (id),
    CONSTRAINT fk_transactions_order   FOREIGN KEY (order_id)   REFERENCES orders (id),
    CONSTRAINT ck_transactions_type    CHECK (type IN ('DEPOSIT', 'WITHDRAWAL', 'BUY', 'SELL')),
    CONSTRAINT ck_transactions_amount  CHECK (amount > 0),
    CONSTRAINT ck_transactions_balance CHECK (balance_after >= 0),
    CONSTRAINT ck_transactions_order   CHECK ((type IN ('BUY', 'SELL')) = (order_id IS NOT NULL))
);

CREATE INDEX ix_transactions_user_created ON transactions (user_id, created_at);
CREATE INDEX ix_transactions_account      ON transactions (account_id);
CREATE INDEX ix_transactions_order        ON transactions (order_id);
